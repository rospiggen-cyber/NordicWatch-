import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const read=path=>readFile(new URL(path,root),'utf8');
const entry=(await read('cloudflare/adsb-monitor-worker.js'))
  .replace(/^import .*;\r?\n/gm,'')
  .replace(/^export \{KVCatalog\}.*\r?\n/gm,'');
// The standalone Worker is ESM, so use the browser/global UMD branches. Leaving
// require('./aircraft-classifier.js') here makes bundlers resolve a nonexistent
// sibling file even though that CommonJS branch never runs in a Worker.
const shared=(await Promise.all(['aircraft-classifier.js','background-monitor-core.js'].map(read)))
  .map(source=>source
    .replace('typeof module!=="undefined"&&module.exports?require("./aircraft-classifier.js"):root.NordicWatchAircraft','root.NordicWatchAircraft')
    .replace(/if\(typeof module!=="undefined"&&module.exports\)module.exports=api;(?:else )?/g,'')
    .replace(/^[ \t]+$/gm,''));
const parts=['// NordicWatch v1.1 bundled Cloudflare Worker\n// Generated by tools/build-background-worker.mjs.\n',
  ...shared,await read('cloudflare/kv-catalog.mjs'),entry];
await writeFile(new URL('cloudflare/adsb-monitor-worker-bundled.js',root),parts.join('\n'));
